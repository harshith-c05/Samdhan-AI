// --- Summary Statistics -------------------------------------------------------
export function computeDemoStats(artifacts) {
  return {
    total:       artifacts.length,
    documents:   artifacts.filter(a => a.type === 'Document').length,
    dbLogs:      artifacts.filter(a => a.type === 'DB log').length,
    photos:      artifacts.filter(a => a.type === 'Photo').length,
    traces:      artifacts.filter(a => a.type === 'System trace').length,
    critical:    artifacts.filter(a => a.priorityTier === 'Critical').length,
    high:        artifacts.filter(a => a.priorityTier === 'High').length,
    medium:      artifacts.filter(a => a.priorityTier === 'Medium').length,
    low:         artifacts.filter(a => a.priorityTier === 'Low').length,
    corrupted:   artifacts.filter(a => a.corruptionSeverity !== 'None').length,
    duplicates:  artifacts.filter(a => a.duplicate).length,
    // Manual Review Queue count (spec sec 3: low-conf artifacts routed here)
    manualReviewRequired: artifacts.filter(a => a.reviewRequired).length,
    fullyRecoverable:     artifacts.filter(a => a.recoverability === 'FULLY_RECOVERABLE').length,
    mostlyRecoverable:    artifacts.filter(a => a.recoverability === 'MOSTLY_RECOVERABLE').length,
    partiallyRecoverable: artifacts.filter(a => a.recoverability === 'PARTIALLY_RECOVERABLE').length,
    barelyRecoverable:    artifacts.filter(a => a.recoverability === 'BARELY_RECOVERABLE').length,
    avgConfidence:    (artifacts.reduce((s, a) => s + a.classificationConfidence, 0) / artifacts.length).toFixed(1),
    avgIntegrity:     (artifacts.reduce((s, a) => s + a.integrity, 0) / artifacts.length).toFixed(1),
    avgPriorityScore: (artifacts.reduce((s, a) => s + a.priorityScore, 0) / artifacts.length).toFixed(3),
  };
}

