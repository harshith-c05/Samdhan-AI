import { computePriorityScore } from '../engine/priorityEngine.js';

const INC_START = '2026-09-24T14:00:00Z';
const INC_END   = '2026-09-24T22:30:00Z';

// Helper: build full artifact record with spec-compliant scoring
function artifact(fields) {
  const scored = computePriorityScore({
    relevance:               fields.evidenceRelevance,
    integrity:               fields.integrity,
    inferredMtime:           fields.metadata?.timestamps?.inferredMtime,
    incidentStart:           INC_START,
    incidentEnd:             INC_END,
    isDuplicate:             fields.duplicate,
    ssdeepSimilarity:        fields.ssdeepSimilarity ?? 0,
    noisePenalty:            fields.noisePenalty ?? 0,
    // Passed for reviewRequired flag only -- NOT folded into score
    classificationConfidence: fields.classificationConfidence,
  });

  return {
    ...fields,
    priorityScore:       scored.score,
    priorityTier:        scored.tier,
    reviewRequired:      scored.reviewRequired,   // badge only, separate from tier
    priorityExplanation: scored.breakdown,
  };
}

